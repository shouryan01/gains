import { readdir, readFile, writeFile } from "node:fs/promises";
const root = new URL("../packages/db/migrations/", import.meta.url);
const files = (await readdir(root)).filter((file) => file.endsWith(".sql")).sort();
const migrations = await Promise.all(
  files.map(async (file) => ({ name: file, sql: await readFile(new URL(file, root), "utf8") })),
);
await writeFile(
  new URL("../packages/db/src/migrations.generated.ts", import.meta.url),
  `// Generated by scripts/embed-migrations.mjs. Do not edit.\nexport const migrations = ${JSON.stringify(migrations, null, 2)} as const;\n`,
);
